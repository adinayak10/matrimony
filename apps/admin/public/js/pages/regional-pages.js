async function refreshStats(type, id, btn) {
  await busy(btn, async () => {
    try {
      await api(`${TYPES[type].base}/${id}/refresh-stats`, { method: 'POST' });
      toast.success('Member counts recalculated from live data');
      tableFor(type).reload();
    } catch (err) { toast.error(errorMessage(err, 'Could not refresh the stats.')); }
  });
}

async function remove(type, id, row) {
  if (!row) return;
  const cfg = TYPES[type];
  const live = row.isPublished && row.isActive !== false;
  const ok = await confirm({
    title: `Delete the ${cfg.noun} for ${pageName(type, row)}?`,
    message: live
      ? `This page is published. Deleting it breaks an indexed URL: ${liveUrl(row)} will stop working and search engines will drop it.`
      : 'This page is not public right now, but its URL may still have been indexed in the past. Deleting cannot be undone.',
    detail: 'To hide a page without breaking its URL history, switch off Published instead.',
    confirmText: 'Delete page',
    danger: true,
    typed: row.slug || 'DELETE',
  });
  if (!ok) return;
  try {
    await api(`${cfg.base}/${id}`, { method: 'DELETE' });
    toast.success('Page deleted');
    tableFor(type).reload();
  } catch (err) { toast.error(errorMessage(err, 'Could not delete the page.')); }
}

