const wantEdit = new URL(location.href).searchParams.get('edit');
if (wantEdit && /^[a-f0-9]{24}$/i.test(wantEdit)) openEditor(currentType, wantEdit);
else if (wantEdit === 'new') openEditor(currentType, null);
