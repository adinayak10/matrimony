function valueFor(def, page) {
  const v = getPath(page, def.p);
  if (def.type === 'checkbox' || def.type === 'switch') return v === undefined ? !!def.fallback : !!v;
  if (def.kind === 'csv') return listToText(v);
  if (def.kind === 'lines') return listToText(v, '\n');
  if (def.kind === 'localities') return listToText((Array.isArray(v) ? v : []).map((l) => (l && typeof l === 'object' ? l.name : l)), '\n');
  return v == null ? '' : String(v);
}

