async function loadStates() {
  if (statesCache) return statesCache;
  const resp = await api('/states', { method: 'POST', body: { limit: 500 } });
  statesCache = (resp.data || []).slice().sort((a, b) => String(a.name).localeCompare(String(b.name)));
  return statesCache;
}

async function fillStateFilter() {
  if (stateFilter.options.length > 1) return;
  try {
    const states = await loadStates();
    const wanted = new URL(location.href).searchParams.get('state') || '';
    setHtml(stateFilter, html`<option value="">Any state</option>${states.map((s) => html`<option value="${s._id}">${s.name}</option>`)}`);
    // The filter was restored from the URL before its options existed: apply it now.
    if (wanted && states.some((s) => s._id === wanted)) filters.set({ state: wanted });
  } catch (e) { /* the state filter is optional */ }
}

