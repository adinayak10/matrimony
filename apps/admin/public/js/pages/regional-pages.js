const getPath = (obj, path) => path.split('.').reduce((acc, k) => (acc && typeof acc === 'object' ? acc[k] : undefined), obj);
const clone = (v) => (v === undefined ? undefined : JSON.parse(JSON.stringify(v)));
const stripHtml = (s) => String(s).replace(/<[^>]*>/g, ' ').replace(/&[a-z#0-9]+;/gi, ' ');

function collectStrings(value, out) {
  if (typeof value === 'string') { out.push(value); return; }
  if (Array.isArray(value)) { for (const v of value) collectStrings(v, out); return; }
  if (value && typeof value === 'object') {
    for (const [k, v] of Object.entries(value)) if (!REF_KEYS.has(k)) collectStrings(v, out);
  }
}

function countContentWords(page) {
  const parts = [];
  for (const f of CONTENT_FIELDS) if (page[f] !== undefined) collectStrings(page[f], parts);
  const words = new Set();
  for (const part of parts) {
    for (const w of stripHtml(part).toLowerCase().split(/[^a-z0-9ऀ-ॿ]+/iu)) if (w && w.length > 1) words.add(w);
  }
  return words.size;
}

