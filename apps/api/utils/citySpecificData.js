/**
 * Get locality-specific content
 * @param {array} localities - Array of locality objects
 * @returns {string} Formatted locality content
 */
function getLocalityContent(localities) {
  if (!localities || localities.length === 0) return '';
  
  const localityList = localities.slice(0, 5).map(loc => 
    `${loc.name} (${loc.banjaraPopulation} members)`
  ).join(', ');
  
  return `Our community is strongest in ${localityList}, ensuring you find matches in your preferred neighborhood.`;
}

