async function restoreUsers() {
  try {
    console.log('🚀 Starting User Restoration...\n');
    
    await connectDB();
    
    let restored = 0;
    let skipped = 0;
    let errors = 0;
    
    for (const userData of usersToRestore) {
      try {
        // Check if user already exists by ID
        const existingUser = await User.findById(userData._id);
        
        if (existingUser) {
          console.log(`⏭️  Skipping: ${userData.full_name} (${userData.phone}) - ID already exists`);
          skipped++;
          continue;
        }
        
        // Check if phone or email already exists
        const duplicatePhone = await User.findOne({ phone: userData.phone });
        const duplicateEmail = userData.email ? await User.findOne({ email: userData.email }) : null;
        
        if (duplicatePhone || duplicateEmail) {
          console.log(`⚠️  Skipping: ${userData.full_name} (${userData.phone}) - Phone/Email already exists`);
          skipped++;
          continue;
        }
        
        // Create new user with all original data including timestamps
        await User.create(userData);
        console.log(`✅ Restored: ${userData.full_name} (${userData.phone}) - Created: ${userData.createdAt.toLocaleDateString()}`);
        restored++;
      } catch (error) {
        // Handle individual user errors
        if (error.code === 11000) {
          console.log(`⚠️  Duplicate: ${userData.full_name} (${userData.phone}) - ${error.message}`);
          skipped++;
        } else {
          console.error(`❌ Error restoring ${userData.full_name}:`, error.message);
          errors++;
        }
      }
    }
    
    console.log('\n' + '='.repeat(60));
    console.log(`📊 Restoration Summary:`);
    console.log(`   ✅ Restored: ${restored} users`);
    console.log(`   ⏭️  Skipped: ${skipped} users (already exist)`);
    console.log(`   ❌ Errors: ${errors} users`);
    console.log(`   📋 Total: ${usersToRestore.length} users`);
    console.log('='.repeat(60));
    
    if (restored > 0) {
      console.log('\n✅ User restoration completed successfully!');
    } else {
      console.log('\nℹ️  No new users were restored.');
    }
    
    process.exit(0);
  } catch (error) {
    console.error('❌ Restoration failed:', error);
    process.exit(1);
  }
}

